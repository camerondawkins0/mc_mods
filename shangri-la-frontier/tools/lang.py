def build():
    lang = dict(MISC)
    lang.update(GUI)
    for k, text in ACTS.items():
        lang[f"quest.slfrontier.act.{k}"] = text
    for k, (loc, journal) in JOURNAL.items():
        lang[f"quest.slfrontier.{k}.location"] = loc
        lang[f"quest.slfrontier.{k}.journal"] = journal
    for k, text in SKILL_UNLOCKS.items():
        lang[f"skill.slfrontier.{k}.unlock"] = text
    for k, (title, desc, obj) in SIDE_QUESTS.items():
        lang[f"sidequest.slfrontier.{k}.title"] = title
        lang[f"sidequest.slfrontier.{k}.desc"] = desc
        lang[f"sidequest.slfrontier.{k}.objective"] = obj
    for k, (name, lore) in ITEMS.items():
        lang[f"item.slfrontier.{k}"] = name
        if lore:
            lang[f"item.slfrontier.{k}.lore"] = lore
    for k, name in BLOCKS.items():
        lang[f"block.slfrontier.{k}"] = name
    for k, name in ENTITIES.items():
        lang[f"entity.slfrontier.{k}"] = name
        if k != "holy_water":
            lang[f"item.slfrontier.{k}_spawn_egg"] = f"{name} Spawn Egg"
    for k, name in BIOMES.items():
        lang[f"biome.slfrontier.{k}"] = name
    for k, (name, desc) in SKILLS.items():
        lang[f"skill.slfrontier.{k}"] = name
        lang[f"skill.slfrontier.{k}.desc"] = desc
    for k, (name, desc) in STATS.items():
        lang[f"stat.slfrontier.{k}"] = name
        lang[f"stat.slfrontier.{k}.desc"] = desc
    for k, (title, obj) in QUESTS.items():
        lang[f"quest.slfrontier.{k}.title"] = title
        lang[f"quest.slfrontier.{k}.objective"] = obj
    for k, text in LORE.items():
        lang[f"lore.slfrontier.{k}"] = text
    for k, text in DIALOGUE.items():
        lang[f"dialogue.slfrontier.{k}"] = text
    for k, text in OPTIONS.items():
        lang[f"dialogue.slfrontier.option.{k}"] = text
    lang.update(lang_inventory.STRINGS)
    lang.update(lang_overlays.STRINGS)
    lang.update(lang_crafting.STRINGS)
    return lang
